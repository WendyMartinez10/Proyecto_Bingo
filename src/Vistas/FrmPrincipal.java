    private void iniciarJuegoSegunModo() {

        CartonController controller = new CartonController();
        java.util.List<Carton> lista = new java.util.ArrayList<>();

        if ("AUTOMATICO".equals(modo)) {

            for (int i = 1; i <= cantidadCartones; i++) {
                Carton c = controller.generarCartonAutomatico("J" + i);
                lista.add(c);

                FrmCarton ventana = new FrmCarton();
                ventana.recibirCarton(c);
                ventana.setVisible(true);
            }

            juegoController.iniciarJuego(model.juego.TipoJuego.valueOf(tipoJuego), lista);
           panelTombola.setJuegoController(juegoController, false);

        } else {

            for (int i = 1; i <= cantidadCartones; i++) {

                JOptionPane.showMessageDialog(
                        this,
                        "Llenando cartón #" + i,
                        "Cartón Manual",
                        JOptionPane.INFORMATION_MESSAGE
                );

                int[][] numeros = llenarCartonManual();
                Carton c = controller.generarCartonManual("MANUAL_" + i, numeros);
                lista.add(c);

                FrmCarton ventana = new FrmCarton();
                ventana.recibirCarton(c);
                ventana.setVisible(true);
            }

            juegoController.iniciarJuego(model.juego.TipoJuego.valueOf(tipoJuego), lista);
             panelTombola.setJuegoController(juegoController, true);
        }
    }

    public void enviarModo(String tipoJuego, String modo, int cantidadCartones) {

        this.tipoJuego = tipoJuego;
        this.modo = modo;
        this.cantidadCartones = cantidadCartones;

        juegoController = new controller.JuegoController(panelTablero, panelTombola, panelResultados);

        iniciarJuegoSegunModo();
        pnlResultados.add(panelResultados, java.awt.BorderLayout.CENTER);

    }

