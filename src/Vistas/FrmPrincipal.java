    private int[][] llenarCartonManual() {

        limpiarTablaCarton();

        jDialog1.setModal(true);
        jDialog1.setSize(618, 471);
        jDialog1.setLocationRelativeTo(this);
        jDialog1.setVisible(true);
        int[][] matriz = new int[5][5];

        for (int fila = 0; fila < 5; fila++) {
            for (int col = 0; col < 5; col++) {

                if (fila == 2 && col == 2) {
                    tbLlenarCarton.setValueAt("LIBRE", fila, col);
                    matriz[fila][col] = 0;
                    continue;
                }

                boolean valido = false;
                int numero = 0;

                while (!valido) {
                    String input = javax.swing.JOptionPane.showInputDialog(
                            this,
                            "Ingrese número para [" + fila + "," + col + "]\nColumna "
                            + getColumnaLetra(col) + "\nRango permitido: "
                            + obtenerRangoColumna(col),
                            "Ingresar número",
                            javax.swing.JOptionPane.QUESTION_MESSAGE
                    );

                    if (input == null) {

                        jDialog1.setVisible(true);

                        JOptionPane.showMessageDialog(
                                this,
                                "Debe ingresar un número.\nPuede revisar el cartón en la tabla.",
                                "Aviso",
                                JOptionPane.INFORMATION_MESSAGE
                        );

                        continue;
                    }

                    try {
                        numero = Integer.parseInt(input);

                        int min = obtenerMin(col);
                        int max = obtenerMax(col);

                        if (numero < min || numero > max) {
                            javax.swing.JOptionPane.showMessageDialog(this,
                                    "Número fuera de rango.\nDebe estar entre " + min + " y " + max,
                                    "Error",
                                    javax.swing.JOptionPane.ERROR_MESSAGE);
                            continue;
                        }

                        if (existeEnMatriz(matriz, numero)) {
                            javax.swing.JOptionPane.showMessageDialog(this,
                                    "Este número ya fue usado.",
                                    "Repetido",
                                    javax.swing.JOptionPane.ERROR_MESSAGE);
                            continue;
                        }

                        valido = true;

                    } catch (NumberFormatException e) {
                        javax.swing.JOptionPane.showMessageDialog(this,
                                "Debe ingresar un número válido.",
                                "Error",
                                javax.swing.JOptionPane.ERROR_MESSAGE);
                    }
                }

                matriz[fila][col] = numero;
                tbLlenarCarton.setValueAt(numero, fila, col);
            }
        }

        return matriz;
    }

    private boolean existeEnMatriz(int[][] m, int valor) {
        for (int i = 0; i < 5; i++) {
            for (int j = 0; j < 5; j++) {
                if (m[i][j] == valor) {
                    return true;
                }
            }
        }
        return false;
    }

    private void limpiarTablaCarton() {
        for (int fila = 0; fila < 5; fila++) {
            for (int col = 0; col < 5; col++) {
                tbLlenarCarton.setValueAt(null, fila, col);
            }
        }
    }

    private String getColumnaLetra(int col) {
        return switch (col) {
            case 0 ->
                "B (1-15)";
            case 1 ->
                "I (16-30)";
            case 2 ->
                "N (31-45)";
            case 3 ->
                "G (46-60)";
            case 4 ->
                "O (61-75)";
            default ->
                "";
        };
    }

    private String obtenerRangoColumna(int col) {
        return switch (col) {
            case 0 ->
                "1 - 15";
            case 1 ->
                "16 - 30";
            case 2 ->
                "31 - 45";
            case 3 ->
                "46 - 60";
            case 4 ->
                "61 - 75";
            default ->
                "";
        };
    }

    private int obtenerMin(int col) {
        return new int[]{1, 16, 31, 46, 61}[col];
    }

    private int obtenerMax(int col) {
        return new int[]{15, 30, 45, 60, 75}[col];
    }


