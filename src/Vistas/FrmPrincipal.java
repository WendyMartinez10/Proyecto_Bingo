    private void mnCartonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mnCartonActionPerformed

        if (juegoController == null) {
            JOptionPane.showMessageDialog(this,
                    "Debes iniciar un juego antes de agregar cartones.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        String[] opciones = {"Automático", "Manual", "Cancelar"};

        int opcion = JOptionPane.showOptionDialog(
                this,
                "¿Cómo desea generar el nuevo cartón?",
                "Nuevo Cartón",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[0]
        );

        if (opcion == 2 || opcion == JOptionPane.CLOSED_OPTION) {
            return;
        }

        CartonController controller = new CartonController();
        Carton cartonNuevo;

        if (opcion == 0) {

            String nombre = "EXTRA_" + (int) (Math.random() * 99);
            cartonNuevo = controller.generarCartonAutomatico(nombre);

            JOptionPane.showMessageDialog(this,
                    "Cartón automático generado correctamente.");
        } else {

            JOptionPane.showMessageDialog(this,
                    "Llenará un nuevo cartón manualmente.");

            int[][] valores = llenarCartonManual();

            String nombre = "MANUAL_EXTRA_" + (int) (Math.random() * 9999);
            cartonNuevo = controller.generarCartonManual(nombre, valores);

            JOptionPane.showMessageDialog(this,
                    "Cartón manual creado correctamente.");
        }

        FrmCarton ventana = new FrmCarton();
        ventana.recibirCarton(cartonNuevo);
        ventana.setVisible(true);

        juegoController.agregarCarton(cartonNuevo);

        JOptionPane.showMessageDialog(this,
                "Cartón agregado al juego satisfactoriamente.");


    }//GEN-LAST:event_mnCartonActionPerformed

